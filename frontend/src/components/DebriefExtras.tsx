import {useEffect, useMemo, useState} from 'react';
import {LineChart, Line, XAxis, YAxis, CartesianGrid, Tooltip, ResponsiveContainer} from 'recharts';
import {apiErrorMessage, getDriverTrack, exportDriverDebrief} from '../services/api';

export function TrackMap({year,round,driver,lap,cornerComparisons}: {year:number;round:number;driver:number;lap:number;cornerComparisons:any[]}){
 const [map,setMap]=useState<any>(null),[error,setError]=useState(''),[loading,setLoading]=useState(false);
 const windows=cornerComparisons.map(z=>z.window_pct as number[]);
 const boundsKey=windows.map(b=>b.join(',')).join(';');
 useEffect(()=>{
   let cancel=false;setLoading(true);setError('');setMap(null);
   getDriverTrack(year,round,driver,lap,windows).then(x=>{if(!cancel)setMap(x)}).catch(e=>{if(!cancel)setError(apiErrorMessage(e,'Track map unavailable'))}).finally(()=>{if(!cancel)setLoading(false)});
   return ()=>{cancel=true}
 },[year,round,driver,lap,boundsKey]);
 const pts=map?.points??[];
 const coords=useMemo(()=>{
   if(!pts.length)return {line:'',markers:[] as any[]};
   const minX=Math.min(...pts.map((p:any)=>p.x)),maxX=Math.max(...pts.map((p:any)=>p.x));
   const minY=Math.min(...pts.map((p:any)=>p.y)),maxY=Math.max(...pts.map((p:any)=>p.y));
   const scale=Math.min(600/Math.max(1,maxX-minX),360/Math.max(1,maxY-minY));
   const sx=(x:number)=>30+(x-minX)*scale,sy=(y:number)=>390-(y-minY)*scale;
   return {line:pts.map((p:any)=>`${sx(p.x).toFixed(1)},${sy(p.y).toFixed(1)}`).join(' '),
           markers:(map.markers??[]).map((p:any)=>({...p,sx:sx(p.x),sy:sy(p.y)}))};
 },[map]);
 return <div className="card"><div className="card-head"><div><div className="kicker">TRACK MAP · PUBLIC XY</div><h3>Inferred braking-zone markers</h3></div><span className="tiny-badge">REFERENCE LAP {lap}</span></div>
   {loading?<p>Loading location observations…</p>:error?<p className="muted-note">{error}</p>:map?.ready?<>
    <div style={{width:'100%',overflowX:'auto'}}><svg viewBox="0 0 690 430" style={{maxWidth:740,width:'100%',background:'#0d141d',borderRadius:12}} role="img" aria-label="Approximate OpenF1 XY circuit map with inferred braking zone markers">
      <polyline points={coords.line} fill="none" stroke="#e6ebf3" strokeWidth="4" strokeLinecap="round" strokeLinejoin="round"/>
      {coords.markers.map((m:any)=><g key={m.id}><circle cx={m.sx} cy={m.sy} r="12" fill="#e10600" stroke="#fff" strokeWidth="1"/><text x={m.sx} y={m.sy+4} textAnchor="middle" fill="white" fontSize="11" fontWeight="700">{m.id}</text></g>)}
    </svg></div><p className="muted-note">{map.note}</p>
   </>:<p className="muted-note">{map?.reason??'Location data not available for this selected lap.'}</p>}
 </div>
}

export function SteeringVideoExperiment(){
 const [rows,setRows]=useState<{video_elapsed_s:number;estimated_rotation_deg:number;confidence:string}[]>([]);
 const [error,setError]=useState(''); const [fileName,setFileName]=useState('');
 async function load(file:File|undefined){
  if(!file)return;
  setError('');setRows([]);setFileName(file.name);
  try{
   if(file.size>2_000_000)throw new Error('CSV must be under 2MB');
   const lines=(await file.text()).trim().split(/\r?\n/);
   const headers=lines.shift()?.split(',').map(s=>s.trim())??[];
   const t=headers.indexOf('video_elapsed_s'), a=headers.indexOf('estimated_rotation_deg'),q=headers.indexOf('confidence');
   if(t<0||a<0)throw new Error('Expected video_elapsed_s and estimated_rotation_deg columns');
   const parsed=lines.map(line=>{const cells=line.split(',');return {video_elapsed_s:Number(cells[t]),estimated_rotation_deg:Number(cells[a]),confidence:q>=0?cells[q]:'unknown'}}).filter((p,i)=>{const cells=lines[i]?.split(',')??[];return cells[a]?.trim()!=='' && Number.isFinite(p.video_elapsed_s)&&Number.isFinite(p.estimated_rotation_deg)});
   if(!parsed.length)throw new Error('No valid estimated rotation samples');
   setRows(parsed.slice(0,1000));
  }catch(e){setError(e instanceof Error?e.message:String(e))}
 }
 return <div className="card"><div className="card-head"><div><div className="kicker">OPTIONAL RESEARCH · VIDEO COMPUTER VISION</div><h3>Import a video-derived steering estimate</h3></div><span className="tiny-badge">NOT OFFICIAL STEERING DATA</span></div>
   <p><strong>You do not need this for normal driver comparisons.</strong> This optional tool displays a CSV generated by <code>backend/scripts/estimate_steering_video.py</code> from footage you are permitted to process. It estimates visible wheel-feature rotation, <strong>not official steering angle</strong>. The video and OpenF1 traces are not synchronized.</p>
   <label className="benchmark-upload" style={{display:'inline-flex',margin:'9px 0 14px'}}>UPLOAD OPTIONAL STEERING CSV<input type="file" accept=".csv,text/csv" onChange={e=>void load(e.target.files?.[0])}/></label>
   {error&&<p className="muted-note">{error}</p>}
   {rows.length>0&&<><p className="muted-note">{fileName} · {rows.length} parsed observations · video seconds, not race-lap progress</p><ResponsiveContainer width="100%" height={250}><LineChart data={rows}><CartesianGrid stroke="#202833" strokeDasharray="3 5"/><XAxis dataKey="video_elapsed_s" stroke="#657181" unit=" s"/><YAxis stroke="#657181" unit="°"/><Tooltip contentStyle={{background:'#0d131b',border:'1px solid #29313d'}}/><Line type="linear" dataKey="estimated_rotation_deg" stroke="#f97373" dot={false} name="Estimated image rotation (°)"/></LineChart></ResponsiveContainer></>}
   <p className="muted-note">No steering estimate is generated unless footage is supplied and the optional script is run. Tracking confidence flags are not calibrated uncertainty intervals. Do not use this trace to diagnose oversteer or vehicle balance.</p>
 </div>
}

export function DebriefExport({report}:{report:any}){
 const [error,setError]=useState(''),[busy,setBusy]=useState(false);
 async function download(format:'md'|'pdf'){
  setBusy(true);setError('');
  try{
   const blob=await exportDriverDebrief(report,format);
   const url=URL.createObjectURL(blob);
   const link=document.createElement('a');link.href=url;link.download=`driver_debrief_${report.year}_${report.round}.${format}`;
   document.body.appendChild(link);link.click();link.remove();URL.revokeObjectURL(url);
  }catch(e){setError(apiErrorMessage(e,'Export failed'))}finally{setBusy(false)}
 }
 return <div className="card"><div className="card-head"><div><div className="kicker">PORTFOLIO EVIDENCE</div><h3>Download engineering debrief</h3></div></div><div style={{display:'flex',gap:10,flexWrap:'wrap'}}>
    <button type="button" className="run-btn" disabled={busy} onClick={()=>void download('md')}>EXPORT MARKDOWN</button>
    <button type="button" className="run-btn" disabled={busy} onClick={()=>void download('pdf')}>EXPORT PDF</button>
   </div>{error&&<p className="muted-note">{error}</p>}<p className="muted-note">Both downloads contain the full loaded one-to-many debrief, with the reference driver and each selected comparison.  The reports include uncertainty and unavailable-channel notes; CV estimates are excluded unless separately documented.</p>
 </div>
}
